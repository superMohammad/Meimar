/**
 * Copy the DuckDB-WASM runtime into `public/duckdb` so the app serves it itself.
 *
 * The alternative is jsDelivr, which makes every page load depend on a third
 * party CDN. Only the exception-handling build is copied: every browser that
 * supports WebAssembly threads-free exception handling can run it, and shipping
 * the MVP fallback as well would add another 40 MB to the tree for browsers we
 * are not targeting.
 */

import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(projectRoot, "node_modules", "@duckdb", "duckdb-wasm", "dist");
const destination = join(projectRoot, "public", "duckdb");

const ASSETS = ["duckdb-eh.wasm", "duckdb-browser-eh.worker.js"];

await mkdir(destination, { recursive: true });
for (const asset of ASSETS) {
  await copyFile(join(source, asset), join(destination, asset));
  console.log(`copied ${asset}`);
}

/**
 * On compression, so nobody re-derives this the hard way.
 *
 * The engine is 34 MB on disk, which looks alarming for a phone. It is not:
 * `next start` gzips `application/wasm`, and the module goes over the wire at
 * 8.1 MB, decompressing to a byte-identical copy. A `HEAD` request hides this
 * -- it reports the full `Content-Length` and no `Content-Encoding` -- so check
 * with `curl --compressed -w '%{size_download}'` on a GET, never `curl -I`.
 *
 * Shipping a pre-compressed `.wasm.gz` beside it was tried and removed. It
 * duplicates what the server already does, and serving it through the proxy
 * double-compresses: Next gzips the already-gzipped body for transfer, the
 * browser strips one layer, and the worker receives gzip bytes where it expects
 * a module.
 *
 * Worth re-checking behind a CDN or reverse proxy, where compression of
 * `application/wasm` is the edge's job and is not always on by default.
 */

/**
 * Emit the service worker that caches the engine, with the installed
 * `@duckdb/duckdb-wasm` version baked into its cache name.
 *
 * Generated rather than hand-written for one reason: the cache has to be
 * invalidated when the engine changes, and the only thing that changes it is a
 * version bump. Deriving the name here means an upgrade drops the old cache on
 * the next activation without anyone remembering to bump a constant. It also
 * means the worker is regenerated by the same `prebuild` step that copies the
 * engine, so the two can never disagree.
 */
const pkg = JSON.parse(
  await readFile(join(projectRoot, "node_modules", "@duckdb", "duckdb-wasm", "package.json"), "utf8"),
);

const serviceWorker = `/**
 * GENERATED by scripts/copy-duckdb-assets.mjs — do not edit.
 *
 * Caches the DuckDB engine in Cache Storage. The module is 34.3 MB decoded,
 * which is above Chrome's per-entry HTTP cache limit, so \`Cache-Control:
 * immutable\` is silently ignored for it and every visit re-downloads ~8 MB.
 * Cache Storage has no such per-entry cap.
 *
 * Deliberately narrow: it answers for \`/duckdb/\` on this origin and nothing
 * else. Every other request -- pages, Parquet range reads, map tiles -- is left
 * entirely alone, so a fault here cannot serve anyone a stale page or a
 * truncated data read.
 */
const CACHE = "meimar-duckdb-${pkg.version}";
const PREFIX = "/duckdb/";

self.addEventListener("install", () => {
  // Take over as soon as possible; the previous worker has nothing in flight
  // that matters, because this only ever serves immutable engine files.
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      // Drop caches from older engine versions. Their bytes are dead weight
      // against the origin quota and will never be requested again.
      const names = await caches.keys();
      await Promise.all(
        names
          .filter((name) => name.startsWith("meimar-duckdb-") && name !== CACHE)
          .map((name) => caches.delete(name)),
      );
      await self.clients.claim();
    })(),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  // A range request must never be answered from a whole-file cache entry, and
  // must never be stored as though it were the whole file.
  if (request.headers.has("range")) return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (!url.pathname.startsWith(PREFIX)) return;

  event.respondWith(
    (async () => {
      const cache = await caches.open(CACHE);
      const hit = await cache.match(request);
      if (hit) return hit;

      const response = await fetch(request);
      // Only a complete, successful, same-origin response is worth keeping.
      if (response.status === 200 && response.type === "basic") {
        // Not awaited: the caller should not wait on a write to a cache.
        event.waitUntil(cache.put(request, response.clone()));
      }
      return response;
    })(),
  );
});
`;

await writeFile(join(projectRoot, "public", "duckdb-sw.js"), serviceWorker);
console.log(`generated public/duckdb-sw.js (cache meimar-duckdb-${pkg.version})`);
